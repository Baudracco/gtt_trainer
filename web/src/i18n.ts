/** Compile-time dictionary key shared by the three interface languages. */
export type TextKey = keyof typeof copy;
/** Create a typed dictionary lookup for the chosen language. */
export function translator(language: Language) {
  const index = { es: 0, it: 1, en: 2 }[language];
  return (key: TextKey): string => copy[key][index];
}
/** Typed translation function passed into components without global mutable locale state. */
export type Translate = ReturnType<typeof translator>;
/** Translate known API failures and append a safe diagnostic trace when available. */
export function errorText(error: unknown, t: Translate): string {
  const code = (error as { code?: string })?.code;
  return code && code in copy
    ? t(code as TextKey)
    : error instanceof Error
      ? error.message
      : t('error');
}
